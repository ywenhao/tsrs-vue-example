import assert from 'node:assert/strict'
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('../', import.meta.url))
const output = resolve(root, 'benchmark/generated')
const fileCount = 600
const linesPerFile = 500
const metricCount = 32
const fields = Array.from({ length: metricCount }, (_, index) => `metric${String(index + 1).padStart(2, '0')}`)
const number = index => String(index).padStart(4, '0')

function renderModel(index) {
  const id = number(index)
  const name = `Entity${id}`
  const previous = index === 0 ? null : number(index - 1)
  const lines = [
    '// Generated by bun run generate:bench. Every line belongs to the synthetic workload.',
    previous === null
      ? 'type RelatedEntity = { id: string; title: string; metric01: number }'
      : `import type { Entity${previous} as RelatedEntity } from './entity-${previous}'`,
    '',
    `export interface ${name} {`,
    '  readonly id: string',
    '  title: string',
    "  status: 'draft' | 'active' | 'archived'",
    '  active: boolean',
    '  createdAt: Date',
    "  related?: Pick<RelatedEntity, 'id' | 'title' | 'metric01'>",
    ...fields.map(field => `  ${field}: number`),
    '}',
    '',
    `export type ${name}Key = keyof ${name}`,
    `export type ${name}Patch = Partial<Omit<${name}, 'id' | 'createdAt'>>`,
    `export type ${name}Summary = Readonly<{ label: string; total: number; active: boolean }>`,
    `export type ${name}Public = Readonly<Pick<${name}, 'id' | 'title' | 'status'>>`,
    `export type ${name}Change = { [K in keyof ${name}]-?: { field: K; before: ${name}[K]; after: ${name}[K] } }[keyof ${name}]`,
    `export type ${name}Filters = { [K in keyof ${name}]?: Readonly<{ value: ${name}[K]; operator: 'eq' | 'neq' }> }`,
    `export type ${name}MetricKey = ${fields.map(field => `'${field}'`).join(' | ')}`,
    `export type ${name}MetricValues = { [K in ${name}MetricKey]: ${name}[K] }`,
    '',
    `export function create${name}(seed: number): ${name} {`,
    '  return {',
    `    id: 'entity-${id}-' + seed,`,
    `    title: 'Entity ${id} #' + seed,`,
    "    status: seed % 2 === 0 ? 'active' : 'draft',",
    '    active: seed % 2 === 0,',
    '    createdAt: new Date(2026, 0, (seed % 28) + 1),',
    ...fields.map((field, fieldIndex) => `    ${field}: seed + ${(index * 17 + fieldIndex * 7) % 101},`),
    '  }',
    '}',
    '',
    `export function project${name}<K extends keyof ${name}>(entity: ${name}, keys: readonly K[]): Pick<${name}, K> {`,
    `  const result = {} as Pick<${name}, K>`,
    '  for (const key of keys) {',
    '    result[key] = entity[key]',
    '  }',
    '  return result',
    '}',
    '',
    `export function patch${name}(entity: ${name}, patch: ${name}Patch): ${name} {`,
    '  return { ...entity, ...patch }',
    '}',
    '',
    `export function summarize${name}(entity: ${name}): ${name}Summary {`,
    '  return {',
    '    label: entity.title.trim() || entity.id,',
    '    total: metricKeys.reduce((sum, key) => sum + entity[key], 0),',
    "    active: entity.active && entity.status !== 'archived',",
    '  }',
    '}',
    '',
  ]

  for (const field of fields) {
    lines.push(
      `export function update${name}${field}(entity: ${name}, value: number): ${name} {`,
      '  const nextValue = Number.isFinite(value) ? Math.round(value) : 0',
      '  return {',
      '    ...entity,',
      `    ${field}: Math.max(0, nextValue),`,
      '  }',
      '}',
      '',
    )
  }
  lines.push('export const metricKeys = [', ...fields.map(field => `  '${field}',`), `] as const satisfies readonly ${name}MetricKey[]`, '')
  assert.ok(lines.length <= linesPerFile, 'Model template is larger than its line budget')

  for (let index = 0; lines.length < linesPerFile; index++) {
    const first = fields[index % metricCount]
    const second = fields[(Math.floor(index / metricCount) + index + 1) % metricCount]
    lines.push(`export type ${name}Projection${String(index + 1).padStart(3, '0')} = Readonly<Pick<${name}, 'id' | '${first}' | '${second}'>>`)
  }
  return finish(lines)
}

function renderComponent(index) {
  const id = number(index)
  const modelId = number(index % 100)
  const entity = `Entity${modelId}`
  const peer = index === 0 ? null : number(Math.floor((index - 1) / 2))
  const lines = [
    '<!-- Generated by bun run generate:bench. Vue script and template expressions are type checked. -->',
    '<script setup lang="ts">',
    "import { computed, reactive, ref } from 'vue'",
    `import { create${entity}, metricKeys, project${entity}, summarize${entity} } from '../models/entity-${modelId}'`,
    `import type { ${entity} } from '../models/entity-${modelId}'`,
    ...(peer === null ? [] : [`import PeerComponent from './Component${peer}.vue'`]),
    '',
    'const props = withDefaults(defineProps<{',
    '  title?: string',
    '  start?: number',
    '}>(), {',
    `  title: 'Component ${id}',`,
    `  start: ${index},`,
    '})',
    '',
    'const emit = defineEmits<{',
    '  change: [value: number]',
    '}>()',
    'const count = defineModel<number>({ default: 0 })',
    `const state = reactive(create${entity}(props.start))`,
    "const query = ref('')",
    `const selectedStatus = ref<${entity}['status']>('active')`,
    'const visibleFields = computed(() => metricKeys.filter(field => field.includes(query.value)))',
    `const identity = computed(() => project${entity}(state, ['id', 'title', 'status'] as const))`,
    `const summary = computed(() => summarize${entity}(state))`,
    '',
    'function adjust(amount: number): void {',
    '  count.value += amount',
    '  state.metric01 += amount',
    "  emit('change', count.value)",
    '}',
    '',
    'function updateTitle(value: string): void {',
    '  state.title = value.trim() || props.title',
    '  state.status = selectedStatus.value',
    '}',
    '',
    ...(peer === null ? [] : [
      'function handlePeerChange(value: number): void {',
      '  state.metric02 = value',
      '}',
      '',
    ]),
  ]

  for (const field of fields) {
    lines.push(`const ${field} = computed(() => {`, `  return Math.round(state.${field} + count.value)`, '})')
  }

  lines.push(
    '</script>',
    '',
    '<template>',
    `  <article class="entity-card" id="component-${id}">`,
    '    <header>',
    '      <h2>{{ props.title }} / {{ identity.title }}</h2>',
    '      <p>{{ summary.label }} · {{ summary.total.toFixed(2) }}</p>',
    '      <input v-model="query" aria-label="Search metrics" />',
    '      <button type="button" @click="updateTitle(query)">Update title</button>',
    '    </header>',
    '    <p>{{ visibleFields.join(", ") }}</p>',
    ...(peer === null ? [] : ['    <PeerComponent :title="identity.title" :start="metric01" @change="handlePeerChange" />']),
  )

  for (const field of fields) {
    lines.push(
      `    <section class="metric" id="field-${id}-${field}">`,
      `      <h3>{{ identity.title }} / ${field}</h3>`,
      `      <p>{{ ${field}.toFixed(2) }}</p>`,
      `      <p>{{ state.${field} > 50 ? 'high' : 'normal' }}</p>`,
      `      <button type="button" @click="adjust(1)">Increase {{ ${field} }}</button>`,
      `      <small v-if="${field} >= 0">{{ summary.total.toFixed(1) }}</small>`,
      '      <span>{{ identity.status.toUpperCase() }}</span>',
      '    </section>',
    )
  }

  const suffix = [
    '  </article>',
    '</template>',
    '',
    '<style scoped>',
    '.entity-card {',
    '  display: grid;',
    '  gap: 16px;',
    '  padding: 24px;',
    '  border: 1px solid #dbe5df;',
    '  border-radius: 12px;',
    '}',
    '.metric {',
    '  display: grid;',
    '  grid-template-columns: repeat(2, minmax(0, 1fr));',
    '  gap: 8px;',
    '  padding: 12px;',
    '  background: #f4f8f5;',
    '}',
    'button {',
    '  min-height: 36px;',
    '  cursor: pointer;',
    '}',
    '</style>',
  ]
  assert.ok(lines.length + suffix.length <= linesPerFile, 'Vue template is larger than its line budget')
  for (let index = 0; lines.length + suffix.length < linesPerFile; index++) {
    const first = fields[index % metricCount]
    const second = fields[(Math.floor(index / metricCount) + index + 1) % metricCount]
    lines.push(`    <p v-if="${first} >= ${second}" class="comparison">${first} / ${second}: {{ (${first} - ${second}).toFixed(2) }}</p>`)
  }
  lines.push(...suffix)
  return finish(lines)
}

function finish(lines) {
  assert.equal(lines.length, linesPerFile)
  return lines.join('\n') + '\n'
}

export function verifyCorpus() {
  let bytes = 0
  for (const [folder, extension] of [['models', '.ts'], ['components', '.vue']]) {
    const directory = resolve(output, folder)
    const files = readdirSync(directory).filter(name => name.endsWith(extension)).sort()
    assert.equal(files.length, fileCount, `${folder} must contain exactly ${fileCount} ${extension} files`)
    for (const name of files) {
      const content = readFileSync(resolve(directory, name), 'utf8')
      assert.ok(content.endsWith('\n'), `${name} must end with a newline`)
      assert.equal(content.split('\n').length - 1, linesPerFile, `${name} must contain exactly ${linesPerFile} lines`)
      bytes += Buffer.byteLength(content)
    }
  }
  return { tsFiles: fileCount, vueFiles: fileCount, linesPerFile, totalLines: fileCount * 2 * linesPerFile, bytes }
}

function generate() {
  rmSync(output, { recursive: true, force: true })
  mkdirSync(resolve(output, 'models'), { recursive: true })
  mkdirSync(resolve(output, 'components'), { recursive: true })
  for (let index = 0; index < fileCount; index++) {
    writeFileSync(resolve(output, 'models', `entity-${number(index)}.ts`), renderModel(index))
    writeFileSync(resolve(output, 'components', `Component${number(index)}.vue`), renderComponent(index))
  }
  const summary = verifyCorpus()
  writeFileSync(resolve(output, 'manifest.json'), JSON.stringify({ generatorVersion: 2, ...summary }, null, 2) + '\n')
  return summary
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const summary = process.argv.includes('--check') ? verifyCorpus() : generate()
  console.log(`${summary.tsFiles} TypeScript + ${summary.vueFiles} Vue files, ${summary.linesPerFile} lines each`)
  console.log(`${summary.totalLines.toLocaleString('en-US')} total lines; ${(summary.bytes / 1024 / 1024).toFixed(2)} MiB`)
}
